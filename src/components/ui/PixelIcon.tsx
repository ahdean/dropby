export type IconName = keyof typeof ICONS;

function toPath(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let run = 1;
      while (row[x + run] === "#") run++;
      d += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [name, { d: toPath(rows), grid: rows.length }]),
) as Record<IconName, { d: string; grid: number }>;

export function PixelIcon({
  name,
  size = 18,
  className,
  title,
}: {
  name: IconName;
  size?: number;
  className?: string;
  /** Give a title only when the icon stands alone without a text label. */
  title?: string;
}) {
  return (
    <svg
      viewBox={`0 0 ${PATHS[name].grid} ${PATHS[name].grid}`}
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      className={className}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      <path d={PATHS[name].d} />
    </svg>
  );
}
